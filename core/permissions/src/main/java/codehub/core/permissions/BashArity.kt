    fun arityFor(command: String): Int {
        val tokens = command.trim().split(Regex("\\s+")).filter { it.isNotEmpty() }
        if (tokens.isEmpty()) return 0
        var maxArity = 1
        var accumulated = tokens.first()
        table[accumulated]?.let { maxArity = it }
        for (i in 1 until tokens.size) {
            accumulated += " " + tokens[i]
            table[accumulated]?.let { maxArity = it }
        }
        return maxArity
    }

    fun describe(command: String): String {
        val arity = arityFor(command)
        val tokens = command.trim().split(Regex("\\s+")).filter { it.isNotEmpty() }
        return if (tokens.size >= arity) {
            tokens.subList(0, arity).joinToString(" ")
        } else {
            tokens.joinToString(" ")
        }
    }
